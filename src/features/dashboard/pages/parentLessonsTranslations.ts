// Category normalization to canonical English ID
export function getCanonicalCategory(categoryName?: string): string {
  if (!categoryName) return '';
  const trimmed = categoryName.trim();
  for (const [key, mapping] of Object.entries(PARENT_LESSON_CATEGORIES)) {
    if (
      key.toLowerCase() === trimmed.toLowerCase() ||
      mapping.en.toLowerCase() === trimmed.toLowerCase() ||
      mapping.hi === trimmed ||
      mapping.gu === trimmed
    ) {
      return key;
    }
  }
  return categoryName;
}

export function getLocalizedCategory(categoryName: string | undefined, lang: LessonsLanguage): string {
  if (!categoryName) return '';
  const canonical = getCanonicalCategory(categoryName);
  const entry = PARENT_LESSON_CATEGORIES[canonical];
  if (entry && entry[lang]) {
    return entry[lang];
  }
  return categoryName;
}

export function getLocalizedTopicTitle(topicId: string | number | undefined, fallbackTitle: string, lang: LessonsLanguage): string {
  const tid = topicId !== undefined ? String(topicId) : '';
  const entry = PARENT_LESSON_TOPICS[tid];
  if (entry && entry[lang]) {
    return entry[lang];
  }
  if (fallbackTitle) {
    const trimmedFallback = fallbackTitle.trim().toLowerCase();
    for (const item of Object.values(PARENT_LESSON_TOPICS)) {
      if (item.en.trim().toLowerCase() === trimmedFallback && item[lang]) {
        return item[lang];
      }
    }
  }
  return fallbackTitle || '';
}

