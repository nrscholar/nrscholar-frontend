export function getCanonicalCategory(cat?: string): string {
  if (!cat) return '';
  const trimmed = cat.trim();
  const lower = trimmed.toLowerCase();
  return CANONICAL_CATEGORY_MAP[lower] || CANONICAL_CATEGORY_MAP[trimmed] || trimmed;
}

export function getLocalizedCategory(cat: string, lang: string): string {
  const canon = getCanonicalCategory(cat);
  const entry = PARENT_LESSON_CATEGORIES[canon];
  if (!entry) return cat;
  if (lang === 'hi') return entry.hi;
  if (lang === 'gu') return entry.gu;
  return entry.en;
}

export function getLocalizedTopicTitle(
  topic: string | { topicId?: string | number; _id?: string | number; id?: string | number; title?: string },
  lang: string
): string {
  if (!lang || lang === 'en') {
    return typeof topic === 'string' ? topic : topic?.title || '';
  }
  if (typeof topic === 'string') {
    const entry = PARENT_LESSON_TITLES[topic];
    if (entry) {
      if (lang === 'hi' && entry.hi) return entry.hi;
      if (lang === 'gu' && entry.gu) return entry.gu;
    }
    return topic;
  }
  const tid = String(topic?.topicId || topic?.id || topic?._id || '');
  const entry = PARENT_LESSON_TITLES[tid];
  if (entry) {
    if (lang === 'hi' && entry.hi) return entry.hi;
    if (lang === 'gu' && entry.gu) return entry.gu;
  }
  return topic?.title || '';
}

